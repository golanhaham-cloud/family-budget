const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const source = fs.readFileSync(require('path').join(__dirname, '../src/app.jsx'), 'utf8');
const start = source.indexOf('function plannedDateOk(');
const end = source.indexOf('function PlannedExpensesSection(', start);
const ctx = {}; vm.createContext(ctx); vm.runInContext(source.slice(start, end), ctx);
for (const date of ['', null, undefined, '2026-02-30', '2026-13-01', '2026-00-01', '2026-1-01', '2026-11-00']) assert.equal(ctx.plannedDateOk({date}), false, String(date));
assert.equal(ctx.plannedDateOk({date:'2028-02-29'}), true);
assert.equal(ctx.plannedDateOk({date:'2026-11-02'}), true);
const original = [{id:'u',date:'',amount:200},{id:'missing',amount:50},{id:'future',date:'2026-12-15',amount:300},{id:'past',date:'2026-10-01',amount:100}];
const group = ctx.groupPlannedExpenses(original,'2026-11');
assert.deepEqual(Array.from(group.undated,p=>p.id),['u','missing']);
assert.deepEqual(Array.from(group.upcoming,p=>p.id),['future']);
assert.deepEqual(Array.from(group.past,p=>p.id),['past']);
assert.equal(original[0].date, '');
const dated = original.map(p=>p.id==='u'?{...p,date:'2026-11-20'}:p);
assert.deepEqual(Array.from(ctx.groupPlannedExpenses(dated,'2026-11').upcoming,p=>p.id),['u','future']);
console.log('Planned date validation and grouping tests pass');
